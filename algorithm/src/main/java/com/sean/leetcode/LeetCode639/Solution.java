package com.sean.leetcode.LeetCode639;

/**
 * @Author: xionghaiyang
 * @Date: 2026-11-05 17:27
 * @Description: https://leetcode.cn/problems/decode-ways-ii
 * 639. 解码方法 II
 * 一条包含字母 A-Z 的消息通过以下的方式进行了 编码 ：
 * 'A' -> "1"
 * 'B' -> "2"
 * ...
 * 'Z' -> "26"
 * 要 解码 一条已编码的消息，所有的数字都必须分组，然后按原来的编码方案反向映射回字母（可能存在多种方式）。例如，"11106" 可以映射为：
 * "AAJF" 对应分组 (1 1 10 6)
 * "KJF" 对应分组 (11 10 6)
 * 注意，像 (1 11 06) 这样的分组是无效的，因为 "06" 不可以映射为 'F' ，因为 "6" 与 "06" 不同。
 * 除了 上面描述的数字字母映射方案，编码消息中可能包含 '*' 字符，可以表示从 '1' 到 '9' 的任一数字（不包括 '0'）。
 * 例如，编码字符串 "1*" 可以表示 "11"、"12"、"13"、"14"、"15"、"16"、"17"、"18" 或 "19" 中的任意一条消息。
 * 对 "1*" 进行解码，相当于解码该字符串可以表示的任何编码消息。
 * 给你一个字符串 s ，由数字和 '*' 字符组成，返回 解码 该字符串的方法 数目 。
 * 由于答案数目可能非常大，返回 10^9 + 7 的 模 。
 * 1 <= s.length <= 10^5
 * s[i] 是 0 - 9 中的一位数字或字符 '*'
 */
public class Solution {

    private static final int MOD = 1_000_000_007;

    public int numDecodings(String s) {
        int n = s.length();
        char[] str = s.toCharArray();
        long[] dp = new long[n];
        dp[0] = str[0] == '*' ? 9 : str[0] != '0' ? 1 : 0;
        for (int i = 1; i < n; i++) {
            char c0 = str[i - 1], c1 = str[i];
            if (c1 == '*') {
                //1-9
                dp[i] += dp[i - 1] * 9;
                if (c0 == '*') {
                    //11-19,21-26
                    dp[i] += (i - 2 >= 0 ? dp[i - 2] : 1) * 15;
                } else {
                    if (c0 == '1') {
                        //11-19
                        dp[i] += (i - 2 >= 0 ? dp[i - 2] : 1) * 9;
                    } else if (c0 == '2') {
                        //21-26
                        dp[i] += (i - 2 >= 0 ? dp[i - 2] : 1) * 6;
                    }
                }
            } else {
                if (c0 == '*') {
                    if (c1 == '0') {
                        //10,20
                        dp[i] += (i - 2 >= 0 ? dp[i - 2] : 1) * 2;
                    } else {
                        dp[i] += dp[i - 1];
                        if ('1' <= c1 && c1 <= '6') {
                            //11-16,21-26
                            dp[i] += (i - 2 >= 0 ? dp[i - 2] : 1) * 2;
                        } else {
                            dp[i] += i - 2 >= 0 ? dp[i - 2] : 1;
                        }
                    }
                } else {
                    if (c1 == '0') {
                        if (c0 == '1' || c0 == '2') {
                            //10,20
                            dp[i] += i - 2 >= 0 ? dp[i - 2] : 1;
                        }
                    } else {
                        dp[i] += dp[i - 1];
                        if (c0 == '1' || (c0 == '2' && '1' <= c1 && c1 <= '6')) {
                            dp[i] += i - 2 >= 0 ? dp[i - 2] : 1;
                        }
                    }
                }
            }
            dp[i] %= MOD;
        }
        return (int) dp[n - 1];
    }

}
